import { describe, expect, it } from 'vitest'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Documentation link checking.
 *
 * Every relative link in every markdown file must resolve to something that
 * exists. Docs rot silently — a link to a file that was renamed still looks
 * like a link — and this is the cheapest possible guard against it.
 */
const ROOT = fileURLToPath(new URL('../', import.meta.url))

const SKIP_DIRS = new Set([
  'node_modules',
  'dist',
  '.git',
  '.astro',
  '.rex',
  '.hench',
  '.claude',
  '.agents',
  '.sourcevision',
  '.lighthouseci',
])

/**
 * Generated by the n-dx toolkit's `init`, describing that toolkit rather than
 * this project. Their links point at files in the toolkit's own repository, so
 * checking them here would report failures this repository cannot fix.
 */
const NOT_OURS = new Set(['AGENTS.md', 'CLAUDE.md'])

const markdownFiles = (() => {
  const found: string[] = []
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (SKIP_DIRS.has(entry.name)) continue
      const full = join(dir, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (entry.name.endsWith('.md') && !NOT_OURS.has(entry.name)) found.push(full)
    }
  }
  walk(ROOT)
  return found
})()

describe('documentation', () => {
  it('finds markdown to check', () => {
    expect(markdownFiles.length).toBeGreaterThan(5)
  })

  it.each(markdownFiles.map((f) => ({ file: f.slice(ROOT.length) })))(
    '$file has no broken relative links',
    ({ file }) => {
      const full = join(ROOT, file)
      const content = readFileSync(full, 'utf8')
      const broken: string[] = []

      for (const match of content.matchAll(/\[[^\]]*\]\(([^)]+)\)/g)) {
        const target = match[1]!
        // External links, anchors and mail links are out of scope here.
        if (/^(https?:|mailto:|#)/.test(target)) continue

        const [path] = target.split('#')
        if (!path) continue

        const resolved = resolve(dirname(full), path)
        if (!existsSync(resolved)) broken.push(target)
      }

      expect(broken, `broken links in ${file}: ${broken.join(', ')}`).toEqual([])
    },
  )
})

describe('the tutorial series', () => {
  const dir = join(ROOT, 'docs/tutorial')
  const pages = readdirSync(dir)
    .filter((name) => /^\d\d-.*\.md$/.test(name))
    .sort()

  it('has eight numbered pages', () => {
    expect(pages).toHaveLength(8)
    expect(pages[0]).toMatch(/^00-/)
    expect(pages[7]).toMatch(/^07-/)
  })

  it.each(pages)('%s links at least one implementing source file', (page) => {
    const content = readFileSync(join(dir, page), 'utf8')
    // Every page maps a concept to real code.
    expect(content).toMatch(/\]\(\.\.\/\.\.\/(src|\.github|docs)\//)
  })

  it.each(pages)('%s ends with an exercise', (page) => {
    const content = readFileSync(join(dir, page), 'utf8')
    expect(content, `${page} has no exercise`).toMatch(/## Exercise/)
  })

  it.each(pages.slice(0, 7))('%s links to the next page', (page) => {
    const content = readFileSync(join(dir, page), 'utf8')
    expect(content, `${page} has no next link`).toMatch(/\*\*Next:\*\*/)
  })

  it('has an index listing every page', () => {
    const index = readFileSync(join(dir, 'README.md'), 'utf8')
    for (const page of pages) {
      expect(index, `index does not link ${page}`).toContain(page)
    }
  })
})

describe('docs/providers.md', () => {
  const content = readFileSync(join(ROOT, 'docs/providers.md'), 'utf8')
  const models = JSON.parse(readFileSync(join(ROOT, 'models.json'), 'utf8')) as {
    models: Array<{ provider: string; enabled: boolean }>
  }

  it('has a section for every enabled provider', () => {
    for (const model of models.models.filter((m) => m.enabled)) {
      expect(content, `no section for ${model.provider}`).toMatch(
        new RegExp(model.provider.replace('-', '.'), 'i'),
      )
    }
  })

  it('names the environment variable for every provider', () => {
    for (const variable of [
      'ANTHROPIC_API_KEY',
      'OPENAI_API_KEY',
      'GOOGLE_API_KEY',
      'XAI_API_KEY',
      'MISTRAL_API_KEY',
      'DEEPSEEK_API_KEY',
      'TOGETHER_API_KEY',
    ]) {
      expect(content, `missing ${variable}`).toContain(variable)
    }
  })

  it('states a total monthly cost derived from the pricing table', () => {
    expect(content).toMatch(/Monthly/)
    expect(content).toMatch(/\$\d/)
    // The calculation must be reproducible, not just asserted.
    expect(content).toMatch(/inputUsdPerMTok/)
  })

  it('tells the reader to set a spend limit', () => {
    expect(content).toMatch(/spend limit/i)
  })
})

describe('cross-references between the key documents', () => {
  const read = (file: string) => readFileSync(join(ROOT, file), 'utf8')

  it('README links the self-hosting guide and the tutorial', () => {
    const readme = read('README.md')
    expect(readme).toContain('docs/self-hosting.md')
    expect(readme).toContain('docs/tutorial')
  })

  it('self-hosting links the provider guide', () => {
    expect(read('docs/self-hosting.md')).toContain('providers.md')
  })

  it('providers guide links SECURITY and self-hosting', () => {
    const providers = read('docs/providers.md')
    expect(providers).toContain('SECURITY.md')
    expect(providers).toContain('self-hosting.md')
  })
})
