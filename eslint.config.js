// Flat ESLint config. Two rules here are load-bearing rather than stylistic:
//
//   1. Nothing under src/providers or src/runner may import a `node:` builtin
//      or touch process.env. Those modules have to run unchanged in a browser
//      for the "run your own benchmark" feature, so the boundary is enforced
//      by lint rather than by good intentions.
//   2. No lint suppressions. If a rule fires, fix the code.
import js from '@eslint/js'
import tseslint from 'typescript-eslint'

/** Files that must stay runtime-agnostic: no Node builtins, no process.env. */
const RUNTIME_AGNOSTIC = [
  'src/providers/**/*.ts',
  'src/runner/**/*.ts',
  'src/schema/**/*.ts',
  // Pure path/week arithmetic that the runner needs. The rest of src/data does
  // real filesystem work and is deliberately not in this list.
  'src/data/paths.ts',
  // The in-memory migration of older run files. The schema module calls it,
  // and the schema has to run in a browser, so this does too.
  'src/data/migrate.ts',
]

export default tseslint.config(
  {
    ignores: [
      'node_modules/**',
      'dist/**',
      'src/site/dist/**',
      'src/site/.astro/**',
      'coverage/**',
      '.rex/**',
      '.hench/**',
      '.sourcevision/**',
      '.claude/**',
      '.agents/**',
      // Generated by `astro sync` on every build; not ours to lint.
      '.astro/**',
    ],
  },
  js.configs.recommended,
  ...tseslint.configs.recommended,
  {
    files: ['**/*.ts'],
    languageOptions: {
      parserOptions: { projectService: true, tsconfigRootDir: import.meta.dirname },
    },
    rules: {
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_' },
      ],
      '@typescript-eslint/consistent-type-imports': 'error',
      // `== null` is the idiom for "null or undefined", which this codebase
      // relies on: the difference between a provider reporting zero and not
      // reporting at all is load-bearing, and both null and undefined mean the
      // latter. Every other loose comparison is still an error.
      eqeqeq: ['error', 'always', { null: 'ignore' }],
      'no-console': 'off',
    },
  },
  {
    files: RUNTIME_AGNOSTIC,
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: ['node:*'],
              message:
                'Runtime-agnostic code must not import Node builtins. Move filesystem or process work into src/cli.ts or src/data/.',
            },
          ],
        },
      ],
      'no-restricted-properties': [
        'error',
        {
          object: 'process',
          property: 'env',
          message:
            'Runtime-agnostic code must not read process.env. Credentials arrive through AdapterContext; the CLI reads the environment.',
        },
      ],
    },
  },
  {
    files: ['tests/**/*.ts', 'scripts/**/*.ts'],
    rules: { '@typescript-eslint/no-explicit-any': 'off' },
  },
  {
    // Plain-JS build scripts: not covered by the TypeScript program, so the
    // Node and web globals they use have to be declared.
    //
    // The DOM globals are for code inside Playwright `page.evaluate()`
    // callbacks. Those function bodies are serialized and run *in the browser*,
    // so `document` and `getComputedStyle` are genuinely defined there even
    // though the surrounding file is a Node script.
    files: ['scripts/**/*.mjs', '*.config.js', '*.config.mjs'],
    languageOptions: {
      globals: {
        document: 'readonly',
        window: 'readonly',
        getComputedStyle: 'readonly',
        location: 'readonly',
        console: 'readonly',
        Buffer: 'readonly',
        process: 'readonly',
        URL: 'readonly',
        URLSearchParams: 'readonly',
        fetch: 'readonly',
        TextEncoder: 'readonly',
        TextDecoder: 'readonly',
      },
    },
  },
)
